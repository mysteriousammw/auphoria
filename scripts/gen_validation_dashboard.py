#!/usr/bin/env python3
"""Regenerate docs/validation/dashboard.md from the analysis manifests.

Reads every installed analysis's manifest (via the registry), the reference
fixtures (docs/validation/references.yaml), the known-issues file, and writes
a markdown dashboard: per analysis, the tests, reference, maturity and known
issues.

The script is the single source of truth for the dashboard: run it (or the
`auphoria validation` CLI command) after changing any manifest, reference or
known-issue, and it rewrites dashboard.md. It also ENFORCES the maturity
rules: an analysis claiming 'reviewed' or 'validated' without both a named
`reviewer` and a `reference` fails the run with a non-zero exit code.

Usage:
    python scripts/gen_validation_dashboard.py [--out PATH]
    python scripts/gen_validation_dashboard.py --check   # only verify, no write
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

from auphoria.core.errors import AuphoriaError
from auphoria.core.manifest import check_maturity
from auphoria.core.version import __version__

REPO_ROOT = Path(__file__).resolve().parent.parent
REFS_PATH = REPO_ROOT / "docs" / "validation" / "references.yaml"
KNOWN_ISSUES_PATH = REPO_ROOT / "docs" / "validation" / "KNOWN_ISSUES.md"
OUT_PATH = REPO_ROOT / "docs" / "validation" / "dashboard.md"

_MATURITY_ORDER = {"experimental": 0, "tested": 1, "reviewed": 2, "validated": 3}


def _load_references() -> dict:
    with REFS_PATH.open(encoding="utf-8") as fh:
        doc = yaml.safe_load(fh)
    # The file is {version, analyses: {analysis_id: {source, how_produced, values}}}
    return dict(doc.get("analyses", {}))


def _load_known_issues() -> dict[str, list[str]]:
    """Parse KNOWN_ISSUES.md into {analysis_id: [issue, ...]}.

    Lines are grouped under a top-level `## <analysis_id>` heading, matching
    how the file is written. Missing/unattributed issues map to key "_".
    """
    if not KNOWN_ISSUES_PATH.exists():
        return {}
    issues: dict[str, list[str]] = {}
    current = "_"
    for line in KNOWN_ISSUES_PATH.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            current = line[3:].strip()
            issues.setdefault(current, [])
        elif line.strip().startswith("- ") and current is not None:
            issues.setdefault(current, []).append(line.strip()[2:].strip())
    return {k: v for k, v in issues.items() if v}


def _build_dashboard() -> tuple[str, list[str]]:
    from auphoria.core import registry

    infos = registry.discover()
    refs = _load_references()
    known = _load_known_issues()
    problems: list[str] = []

    lines: list[str] = []
    lines.append("# AUPHORIA validation dashboard\n")
    lines.append(
        "Auto-generated by `scripts/gen_validation_dashboard.py`. Do not edit by "
        "hand — change the manifests, `docs/validation/references.yaml` or "
        "`docs/validation/KNOWN_ISSUES.md`, then re-run the script (or "
        "`auphoria validation`).\n"
    )
    lines.append(f"_Generated by AUPHORIA v{__version__}, "
                 f"{len(infos)} analyses._\n")
    lines.append("| ID | Name | Maturity | Reviewer | Reference | Tests | Known issues |")
    lines.append("|----|------|----------|----------|-----------|-------|--------------|")

    ordered = sorted(infos.values(), key=lambda i: (_MATURITY_ORDER.get(str(i.maturity).lower(), 9), i.id))
    for info in ordered:
        m = info.manifest
        maturity = str(m.get("maturity", "")).lower()
        reviewer = str(m.get("reviewer", "")).strip() or "—"
        reference = str(m.get("reference", "")).strip()
        ref_source = (refs.get(info.id) or {}).get("source", "") or reference or "—"
        ref_how = (refs.get(info.id) or {}).get("how_produced", "") or ""

        # Maturity gate: reviewed/validated demand reviewer + reference.
        for problem in check_maturity(m):
            problems.append(f"{info.id}: {problem}")

        tests = ", ".join(_test_listing(info)) or "—"
        issues = "; ".join(known.get(info.id, [])) or "—"

        ref_display = ref_source
        rows = (refs.get(info.id) or {}).get("values") or {}
        if rows and ref_source != "—":
            mets = ", ".join(f"{k}={v['value']}" for k, v in rows.items())
            ref_display = f"{ref_source} ({mets})"
        reference_cell = f"{ref_display} — {ref_how}".replace("|", "\\|")

        lines.append(
            f"| `{info.id}` | {info.name} | **{maturity}** | {reviewer} | "
            f"{reference_cell} | {tests} | {issues} |"
        )
        lines.append("")
        lines.append(f"<details><summary>Reference detail: <code>{info.id}</code></summary>")
        lines.append("")
        lines.append(f"**Source:** {ref_source}")
        lines.append("")
        lines.append(f"**How produced:** {ref_how}")
        lines.append("")
        for k, v in (rows or {}).items():
            lines.append(f"- `{k}` = {v['value']} (tol {v.get('tolerance')})")
        lines.append("")
        lines.append(f"**Known issues:** {issues}")
        lines.append("")
        lines.append("</details>")
        lines.append("")

    return "\n".join(lines), problems


def _test_listing(info) -> list[str]:
    """Names of the analysis's known-answer test file, if it exists."""
    test_dir = info.directory / "tests"
    if not test_dir.is_dir():
        return []
    ids = []
    for path in sorted(test_dir.glob("test_*.py")):
        ids.append(f"`{path.stem}`")
    return ids


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=str(OUT_PATH))
    parser.add_argument("--check", action="store_true", help="verify only, do not write")
    args = parser.parse_args(argv)

    try:
        dashboard, problems = _build_dashboard()
    except AuphoriaError as exc:
        print(f"ERROR: {exc.to_user()}", file=sys.stderr)
        return 1

    if problems:
        print("Validation maturity CHECK FAILED:", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 2

    out = Path(args.out)
    if not args.check:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(dashboard + "\n", encoding="utf-8")
        print(f"Wrote {out}")
    else:
        if out.exists() and out.read_text(encoding="utf-8").strip() == dashboard.strip():
            print(f"OK: {out} is current.")
        else:
            print(f"STALE: {out} would change. Re-run the generator.", file=sys.stderr)
            return 3
    return 0


if __name__ == "__main__":
    sys.exit(main())
